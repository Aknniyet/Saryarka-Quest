// Content was saved once with a legacy Cyrillic encoding. Decode it at the
// boundary so existing translations and records render correctly.
const legacyBytes = new Map(
  Array.from({ length: 256 }, (_, byte) => [
    new TextDecoder("windows-1251").decode(new Uint8Array([byte])),
    byte,
  ])
);

export function fixText(value) {
  if (typeof value !== "string" || !/[РСЃТУв]/.test(value)) return value;
  const bytes = [];
  for (const char of value) {
    const byte = legacyBytes.get(char);
    if (byte === undefined) return value;
    bytes.push(byte);
  }
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(new Uint8Array(bytes));
  } catch {
    return value;
  }
}

export function tr(dict, lang) {
  if (!dict) return "";
  const value = dict[lang] ?? dict.ru ?? "";
  return Array.isArray(value) ? value.map(fixText) : fixText(value);
}
